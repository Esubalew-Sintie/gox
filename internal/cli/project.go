package cli

import (
	"errors"
	"fmt"
	"path/filepath"

	"github.com/esubalew-Sintie/gox/internal/manifest"
	"github.com/esubalew-Sintie/gox/internal/model"
	"github.com/esubalew-Sintie/gox/internal/templates"
)

// project is a loaded gox project.
type project struct {
	root     string
	spec     *manifest.Spec
	manifest *manifest.Manifest
	model    *model.Project
	store    *templates.Store
}

func loadProject(dir string) (*project, error) {
	root, err := filepath.Abs(dir)
	if err != nil {
		return nil, fmt.Errorf("resolve %s: %w", dir, err)
	}
	spec, err := manifest.LoadSpec(root)
	if err != nil {
		if errors.Is(err, manifest.ErrSpecNotFound) {
			return nil, fmt.Errorf("no gox.yaml in %s; run gox new to create a project or -C to point at one", root)
		}
		return nil, err
	}
	m, err := manifest.Load(root)
	if err != nil {
		if errors.Is(err, manifest.ErrNotFound) {
			return nil, fmt.Errorf("no .gox/manifest.json in %s; the project was not generated by this gox", root)
		}
		return nil, err
	}
	p, err := model.FromSpec(spec)
	if err != nil {
		return nil, err
	}
	store, err := templates.New(root)
	if err != nil {
		return nil, err
	}
	return &project{root: root, spec: spec, manifest: m, model: p, store: store}, nil
}
